import { test, expect } from '@playwright/test';
test('quote proposals require approval, recover rows, and can be reversed', async ({page}) => {
  await page.goto('/csv-repair/');
  await page.getByLabel('Choose CSV file').setInputFiles({name:'quotes.csv',mimeType:'text/csv',buffer:Buffer.from('id,name,note\n11,Test,"Unclosed quote\n12,Next,Following row\n17,Other,"Multi-line\nnote that is valid"\n20,Last,"Bad "quote" inside field"')});
  const approve = page.getByRole('checkbox',{name:/Apply suggested quote repairs/});
  await expect(approve).not.toBeChecked();
  await expect(approve).toBeDisabled();
  await page.getByText('Review 2 changed physical lines').click();
  await expect(page.getByText('Line 2:',{exact:false})).toBeVisible();
  await page.getByLabel('I reviewed line 2',{exact:true}).check();
  await expect(approve).toBeDisabled();
  await page.getByLabel('I reviewed line 6',{exact:true}).check();
  await expect(approve).toBeEnabled();
  await approve.check();
  await expect(page.getByText('Showing 4 of 4 data rows.',{exact:false})).toBeVisible();
  await expect(page.getByRole('cell',{name:'Following row',exact:true})).toBeVisible();
  await expect(page.getByText('CSV parsing warning',{exact:false})).toHaveCount(0);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:`test-results/${test.info().project.name}-quote-repair.png`,fullPage:true});
  await approve.uncheck();
  await expect(page.getByText('CSV parsing warning',{exact:false}).first()).toBeVisible();
  await expect(page.getByRole('button',{name:'Before',exact:true})).toHaveAttribute('aria-pressed','true');
});
test('upload, review, reversible cleaning and local downloads', async ({page}) => {
  await page.goto('/csv-repair/');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:`test-results/${test.info().project.name}-upload.png`,fullPage:true});
  const source = 'name,value,empty\n Ada ,0,\nAda,0,\nBea,,\n,,\n';
  await page.getByLabel('Choose CSV file').setInputFiles({name:'synthetic.csv',mimeType:'text/csv',buffer:Buffer.from(source)});
  await expect(page.getByText('synthetic.csv',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'2 Clean',exact:true}).click();
  await page.getByRole('link',{name:'3 Preview',exact:true}).click();
  await page.getByRole('switch',{name:/Trim whitespace/}).check();
  await page.getByRole('switch',{name:/Remove duplicate rows/}).check();
  await page.getByRole('switch',{name:/Remove empty rows/}).check();
  await page.getByRole('button',{name:'After',exact:true}).click();
  await expect(page.getByText('Showing 2 of 2 data rows.',{exact:false})).toBeVisible();
  await page.getByRole('switch',{name:/Remove duplicate rows/}).uncheck();
  await expect(page.getByText('Showing 3 of 3 data rows.',{exact:false})).toBeVisible();
  await page.getByRole('switch',{name:/Remove duplicate rows/}).check();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:`test-results/${test.info().project.name}-review.png`,fullPage:true});
  const originalPromise = page.waitForEvent('download'); await page.getByRole('button',{name:'Download original unchanged'}).click();
  const original = await originalPromise; expect(original.suggestedFilename()).toBe('synthetic.csv');
  const stream = await original.createReadStream(); let content = ''; for await (const chunk of stream!) content += chunk; expect(content).toBe(source);
  const cleanedPromise = page.waitForEvent('download'); await page.getByRole('button',{name:'Download CSV',exact:true}).click(); expect((await cleanedPromise).suggestedFilename()).toBe('synthetic_cleaned.csv');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Start over'}).click(); await expect(page.getByRole('button',{name:/Browse files/})).toBeVisible();
});
